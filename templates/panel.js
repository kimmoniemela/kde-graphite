    d.wallpaperPlugin = 'org.kde.color';
    d.currentConfigGroup = ['Wallpaper', 'org.kde.color', 'General'];
    d.writeConfig('Color', '#111416');
    d.currentConfigGroup = ['General'];
    d.writeConfig('showToolbox', false);
